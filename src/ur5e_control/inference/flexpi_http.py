"""HTTP transport and live-observation adapter for a FlexPi UR5e server.

This module is intentionally separate from :mod:`vla_client`, whose wire
protocol is WebSocket + msgpack.  FlexPi exposes HTTP JSON endpoints instead.
"""

from __future__ import annotations

import base64
from dataclasses import dataclass, field
import json
from typing import Any, Callable, Mapping
from urllib.error import HTTPError, URLError
from urllib.request import ProxyHandler, Request, build_opener

import cv2
import numpy as np


FLEXPI_MODES = (
    "video_dit_joint",
    "video_dit_action_only",
    "action_dit_joint",
    "action_dit_action_only",
)

DEFAULT_FLEXPI_IMAGE_MAP = {
    "third_left_top_rgb": "cam_high",
    "wrist_rgb": "cam_left_wrist",
}

UrlOpen = Callable[..., Any]


class FlexPiHTTPClient:
    """Small synchronous client for FlexPi's ``/health`` and ``/predict`` API."""

    def __init__(
        self,
        server_url: str = "http://127.0.0.1:8000",
        *,
        timeout_s: float = 600.0,
        opener: UrlOpen | None = None,
    ) -> None:
        normalized_url = server_url.rstrip("/")
        if not normalized_url.startswith(("http://", "https://")):
            raise ValueError(
                "FlexPi server_url must use http:// or https://, not ws://"
            )
        if timeout_s <= 0:
            raise ValueError("timeout_s must be positive")
        self.server_url = normalized_url
        self.timeout_s = float(timeout_s)
        # Inference servers commonly run on localhost.  Explicitly bypass
        # HTTP(S)_PROXY so a local /health or /predict request cannot be sent
        # to a corporate proxy and returned as a misleading 502 response.
        self._opener = opener or build_opener(ProxyHandler({})).open

    def health(self) -> dict[str, Any]:
        return self._request("GET", "/health")

    def infer(
        self,
        observation: Mapping[str, Any],
        *,
        mode: str = "action_dit_action_only",
        steps: int = 4,
        seed: int = 42,
        audit: bool = False,
    ) -> dict[str, Any]:
        if mode not in FLEXPI_MODES:
            raise ValueError(f"mode must be one of {', '.join(FLEXPI_MODES)}")
        if not 1 <= steps <= 100:
            raise ValueError("steps must be in [1, 100]")
        if not 0 <= seed < 2**63:
            raise ValueError("seed must be in [0, 2^63)")

        payload = _encode_request(observation)
        payload.update(mode=mode, steps=steps, seed=seed, audit=bool(audit))
        result = self._request("POST", "/predict", payload)
        _validate_action_response(result)
        return result

    def _request(
        self,
        method: str,
        path: str,
        payload: Mapping[str, Any] | None = None,
    ) -> dict[str, Any]:
        body = None
        headers: dict[str, str] = {}
        if payload is not None:
            body = json.dumps(payload, allow_nan=False).encode("utf-8")
            headers["Content-Type"] = "application/json"
        request = Request(
            self.server_url + path,
            data=body,
            headers=headers,
            method=method,
        )
        try:
            with self._opener(request, timeout=self.timeout_s) as response:
                result = json.load(response)
        except HTTPError as exc:
            detail = exc.read().decode("utf-8", errors="replace")
            raise RuntimeError(
                f"FlexPi HTTP {exc.code} from {path}: {detail or exc.reason}"
            ) from exc
        except URLError as exc:
            raise RuntimeError(
                f"Cannot reach FlexPi server at {self.server_url}: {exc.reason}"
            ) from exc
        except TimeoutError as exc:
            raise RuntimeError(
                f"FlexPi request to {path} timed out after {self.timeout_s:g}s; "
                "increase vla.request_timeout_s in the runtime YAML if the "
                "server is still computing"
            ) from exc

        if not isinstance(result, dict):
            raise RuntimeError("FlexPi response must be a JSON object")
        if "error" in result:
            raise RuntimeError(f"FlexPi server error: {result['error']}")
        return result


@dataclass(frozen=True)
class FlexPiRequestAdapter:
    """Map live ``RobotEnv`` observations to the FlexPi UR5e contract.

    Depth is deliberately generated by FlexPi's bundled DA3 estimator.  The
    raw RealSense depth stream isn't registered to the color stream and cannot
    safely be sent as ``rectified_final_grid`` without a separate geometry
    conversion.
    """

    image_map: Mapping[str, str] = field(
        default_factory=lambda: dict(DEFAULT_FLEXPI_IMAGE_MAP)
    )
    expected_rgb_hw: tuple[int, int] = (480, 640)

    def __post_init__(self) -> None:
        object.__setattr__(
            self,
            "image_map",
            {str(source): str(target) for source, target in self.image_map.items()},
        )

    def from_env_obs(
        self,
        env_obs: Mapping[str, Any],
        *,
        instruction: str,
    ) -> dict[str, Any]:
        if not isinstance(instruction, str) or not instruction.strip():
            raise ValueError("FlexPi instruction must be a non-empty string")

        state = _finite_vector(env_obs, "joint_positions", 7)
        if not 0.0 <= state[6] <= 1.0:
            raise ValueError(
                "FlexPi gripper state must be normalized to [0, 1], "
                f"got {state[6]}"
            )
        tcp_pose = _finite_vector(env_obs, "tcp_pose", 6)

        rgb: dict[str, np.ndarray] = {}
        expected_shape = (*self.expected_rgb_hw, 3)
        for env_key, camera_slot in self.image_map.items():
            if env_key not in env_obs:
                raise KeyError(f"env observation is missing RGB key: {env_key}")
            image = np.asarray(env_obs[env_key])
            if image.dtype != np.uint8 or image.shape != expected_shape:
                raise ValueError(
                    f"{env_key} must be uint8 RGB with shape {expected_shape}, "
                    f"got dtype={image.dtype}, shape={image.shape}"
                )
            rgb[camera_slot] = image

        return {
            "instruction": instruction.strip(),
            "state": state,
            "tcp_pose": tcp_pose,
            "rgb": rgb,
            "depth_mode": "da3",
        }


def _finite_vector(
    values: Mapping[str, Any],
    key: str,
    expected_size: int,
) -> np.ndarray:
    if key not in values:
        raise KeyError(f"env observation is missing {key}")
    array = np.asarray(values[key], dtype=np.float64).reshape(-1)
    if array.size != expected_size:
        raise ValueError(f"{key} must contain {expected_size} values, got {array.size}")
    if not np.isfinite(array).all():
        raise ValueError(f"{key} must contain only finite values")
    return array


def _encode_request(observation: Mapping[str, Any]) -> dict[str, Any]:
    required = {"instruction", "state", "tcp_pose", "rgb", "depth_mode"}
    missing = required.difference(observation)
    if missing:
        raise KeyError(f"FlexPi observation is missing: {', '.join(sorted(missing))}")

    rgb = observation["rgb"]
    if not isinstance(rgb, Mapping) or not rgb:
        raise ValueError("FlexPi rgb must be a non-empty mapping")

    result = {
        key: _jsonable(value)
        for key, value in observation.items()
        if key != "rgb"
    }
    result["rgb"] = {
        str(camera): _png_base64(np.asarray(image))
        for camera, image in rgb.items()
    }
    return result


def _png_base64(rgb: np.ndarray) -> str:
    if rgb.dtype != np.uint8 or rgb.ndim != 3 or rgb.shape[2] != 3:
        raise ValueError("RGB images must be uint8 HWC arrays")
    # OpenCV's encoder expects BGR.  Convert explicitly so PIL on the server
    # decodes the original RGB channel order.
    bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
    ok, encoded = cv2.imencode(".png", bgr)
    if not ok:
        raise RuntimeError("failed to encode RGB image as PNG")
    return base64.b64encode(encoded.tobytes()).decode("ascii")


def _jsonable(value: Any) -> Any:
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, Mapping):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    return value


def _validate_action_response(response: Mapping[str, Any]) -> None:
    if "actions" not in response:
        raise RuntimeError("FlexPi response is missing 'actions'")
    actions = np.asarray(response["actions"], dtype=np.float64)
    if actions.ndim != 2 or actions.shape[1] != 7 or actions.shape[0] == 0:
        raise RuntimeError(
            "FlexPi actions must have shape [horizon, 7], "
            f"got {actions.shape}"
        )
    if not np.isfinite(actions).all():
        raise RuntimeError("FlexPi actions contain non-finite values")
